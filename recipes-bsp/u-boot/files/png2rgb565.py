"""Convert a PNG into a C header with big-endian RGB565 pixels.

Used for the U-Boot splash on the LinHT ST7735R display. Supports 8-bit
RGB and RGBA PNGs without interlacing; alpha is blended onto black.
Only the Python standard library is needed.

usage: png2rgb565.py <image.png> <out.h> <width> <height>
"""

import struct
import sys
import zlib


def paeth(a, b, c):
    p = a + b - c
    pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
    if pa <= pb and pa <= pc:
        return a
    return b if pb <= pc else c


def read_png(path):
    data = open(path, "rb").read()
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        sys.exit(f"{path}: not a PNG file")

    pos, idat = 8, b""
    width = height = bpp = None
    while pos < len(data):
        length, kind = struct.unpack(">I4s", data[pos:pos + 8])
        chunk = data[pos + 8:pos + 8 + length]
        pos += 12 + length
        if kind == b"IHDR":
            width, height, depth, ctype, _, _, interlace = \
                struct.unpack(">IIBBBBB", chunk)
            if depth != 8 or ctype not in (2, 6) or interlace:
                sys.exit(f"{path}: need 8-bit RGB/RGBA, non-interlaced")
            bpp = 3 if ctype == 2 else 4
        elif kind == b"IDAT":
            idat += chunk
        elif kind == b"IEND":
            break

    raw = zlib.decompress(idat)
    stride = width * bpp
    rows, prev = [], bytearray(stride)
    for y in range(height):
        base = y * (stride + 1)
        ftype = raw[base]
        line = bytearray(raw[base + 1:base + 1 + stride])
        for x in range(stride):
            a = line[x - bpp] if x >= bpp else 0
            b = prev[x]
            c = prev[x - bpp] if x >= bpp else 0
            if ftype == 1:
                line[x] = (line[x] + a) & 0xff
            elif ftype == 2:
                line[x] = (line[x] + b) & 0xff
            elif ftype == 3:
                line[x] = (line[x] + ((a + b) >> 1)) & 0xff
            elif ftype == 4:
                line[x] = (line[x] + paeth(a, b, c)) & 0xff
        rows.append(line)
        prev = line
    return width, height, bpp, rows


def main():
    if len(sys.argv) != 5:
        sys.exit(__doc__)
    src, dst = sys.argv[1], sys.argv[2]
    want_w, want_h = int(sys.argv[3]), int(sys.argv[4])

    width, height, bpp, rows = read_png(src)
    if (width, height) != (want_w, want_h):
        sys.exit(f"{src}: is {width}x{height}, need {want_w}x{want_h}")

    out = bytearray()
    for line in rows:
        for x in range(width):
            r, g, b = line[x * bpp:x * bpp + 3]
            if bpp == 4:
                alpha = line[x * bpp + 3]
                r, g, b = (r * alpha // 255, g * alpha // 255,
                           b * alpha // 255)
            pixel = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
            out += struct.pack(">H", pixel)

    with open(dst, "w") as f:
        f.write(f"/* Generated by png2rgb565.py from {src.split('/')[-1]}"
                " - do not edit */\n")
        f.write(f"static const u8 linht_splash_img[{len(out)}] = {{\n")
        for i in range(0, len(out), 16):
            f.write("\t" + ", ".join(f"0x{v:02x}" for v in out[i:i + 16])
                    + ",\n")
        f.write("};\n")


if __name__ == "__main__":
    main()
